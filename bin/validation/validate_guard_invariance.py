#!/usr/bin/env python3
"""Is a guard metric measuring the world, or measuring our own configuration?

WHY THIS EXISTS
---------------
The edge-collapse auto-halt was wrong three times in a row, each attempt more
carefully validated than the last:

  Session 515  thresholds calibrated on best-bets-level edges were executed
               against every model's every prediction. Fired 865/865 days.
  2026-08-19   same basis for calibration and execution, but the basis is
               coupled to fleet CONFIGURATION, so the calibration episode was
               an artifact of a fleet swap.
  2026-08-21   demoted to a degeneracy guard after two independent bases showed
               the metric does not move at all.

The invariant process failure was **self-referential calibration**: the
validation data was generated by the system being validated, and no check asked
whether the metric's LEVEL is a property of the world or of our own
configuration. This script is that check. It is one query per metric.

Run it before changing any guard threshold, and monthly in-season.

WHAT IT MEASURES
----------------
For each registered guard metric, over the trailing season:

  1. CHURN COUPLING — Spearman correlation between the daily metric and the
     share of that day's prediction rows coming from `system_id`s younger than
     7 days. On the 2026-08-19 metric this reads **-0.849**: the metric was
     essentially a proxy for experiment-run pollution.

     Note it must be CHURN, not headcount. Correlation against the distinct
     model COUNT was only -0.129 — a review that measured model count called the
     problem directionally right and still under-read it by a factor of six.

  2. SIMPSON CHECK — does a month-over-month move in the pooled metric agree
     with the majority of the models present in BOTH months? A pooled move that
     no incumbent shows is composition, not signal.

Neither check needs a label, a ground truth, or an episode. That is the point:
they are external anchors on a quantity the system generates itself.
"""
import argparse
import sys
from typing import Dict, List, Sequence, Tuple

PROJECT = 'nba-props-platform'

#: |rho| at or above this against churn means the metric tracks configuration.
CHURN_RHO_LIMIT = 0.50

#: How far outside lived behaviour a threshold must sit, as a fraction of the
#: observed floor (or ceiling). This is the convention shared/config/edge_halt.py
#: already states for itself — "0.35 clears the tightest floor by 47%" — so the
#: check enforces the project's own rule rather than inventing a new one.
#:
#: Deliberately NOT an SD-based rule: this metric's standard deviation is
#: dominated by the level shift between fleet generations (2.4 in December, 0.9
#: in March), so "N standard deviations of margin" would measure composition
#: variance and call a perfectly safe floor unsafe.
#:
#: Coupling alone is not a defect — it is true of every model-derived quantity
#: here, and no amount of quarantining removes it. Coupling plus a threshold
#: close enough for ordinary churn to cross it is the defect.
SAFE_RELATIVE_MARGIN = 0.25


#: `threshold`/`direction` let the check ask the question that actually matters:
#: not "is this coupled" (everything model-derived is) but "is the threshold far
#: enough from lived behaviour that configuration churn cannot reach it".
GUARD_METRICS: Dict[str, Dict[str, str]] = {
    # The metric edge_halt is built on, at the raw per-prediction level the
    # 2026-08-19 calibration used.
    'edge_median_per_player_game': {
        'description': 'Median edge per player-game, pooled across models',
        'threshold': 1.4,        # the retired 2026-08-19 halt bar
        'direction': 'below',
        # Kept as a REGRESSION WITNESS, not a live guard: this is what a metric
        # that fires on configuration looks like when this script sees it.
        # Reported, never fails the run.
        'historical': True,
        'sql': """
            SELECT
              game_date,
              APPROX_QUANTILES(edge_pg, 100)[OFFSET(50)] AS metric
            FROM (
              SELECT game_date, player_lookup, game_id,
                     APPROX_QUANTILES(ABS(predicted_points - current_points_line),
                                      100)[OFFSET(50)] AS edge_pg
              FROM `{p}.nba_predictions.player_prop_predictions`
              WHERE game_date BETWEEN @start AND @end
                AND has_prop_line AND current_points_line IS NOT NULL
                AND predicted_points IS NOT NULL
              GROUP BY game_date, player_lookup, game_id
            )
            GROUP BY game_date
        """,
    },
    # The basis edge_halt actually ships with, so a future change is checked
    # against the same yardstick.
    'edge_median_warm_basis': {
        'description': 'Median across warm model families (the shipped basis)',
        'threshold': 0.35,       # the shipped degeneracy bar
        'direction': 'below',
        'sql': None,   # filled in from shared.config.edge_halt at runtime
    },
}

CHURN_SQL = """
    WITH md AS (
      SELECT system_id, game_date
      FROM `{p}.nba_predictions.player_prop_predictions`
      WHERE game_date BETWEEN DATE_SUB(@start, INTERVAL 120 DAY) AND @end
        AND has_prop_line
      GROUP BY system_id, game_date
    ),
    hist AS (
      SELECT system_id, game_date,
             ROW_NUMBER() OVER (PARTITION BY system_id ORDER BY game_date) - 1 AS prior_days
      FROM md
    ),
    rows_by_day AS (
      SELECT p.game_date, p.system_id, COUNT(*) AS n
      FROM `{p}.nba_predictions.player_prop_predictions` p
      WHERE p.game_date BETWEEN @start AND @end AND p.has_prop_line
      GROUP BY p.game_date, p.system_id
    )
    SELECT
      r.game_date,
      SAFE_DIVIDE(SUM(IF(h.prior_days < 7, r.n, 0)), SUM(r.n)) AS young_share,
      COUNT(DISTINCT r.system_id) AS n_models
    FROM rows_by_day r
    JOIN hist h ON h.system_id = r.system_id AND h.game_date = r.game_date
    GROUP BY r.game_date
"""


def _rank(values: Sequence[float]) -> List[float]:
    order = sorted(range(len(values)), key=lambda i: values[i])
    ranks = [0.0] * len(values)
    i = 0
    while i < len(order):
        j = i
        while j + 1 < len(order) and values[order[j + 1]] == values[order[i]]:
            j += 1
        avg = (i + j) / 2.0 + 1.0
        for k in range(i, j + 1):
            ranks[order[k]] = avg
        i = j + 1
    return ranks


def spearman(xs: Sequence[float], ys: Sequence[float]) -> float:
    """Rank correlation. No scipy — this must run anywhere, including CI."""
    if len(xs) < 3:
        return 0.0
    rx, ry = _rank(xs), _rank(ys)
    n = len(rx)
    mx, my = sum(rx) / n, sum(ry) / n
    num = sum((a - mx) * (b - my) for a, b in zip(rx, ry))
    dx = sum((a - mx) ** 2 for a in rx) ** 0.5
    dy = sum((b - my) ** 2 for b in ry) ** 0.5
    return num / (dx * dy) if dx and dy else 0.0


def _client():
    from google.cloud import bigquery
    return bigquery.Client(project=PROJECT)


def _run(client, sql, start, end):
    from google.cloud import bigquery
    cfg = bigquery.QueryJobConfig(query_parameters=[
        bigquery.ScalarQueryParameter('start', 'DATE', start),
        bigquery.ScalarQueryParameter('end', 'DATE', end),
    ])
    # Only format templates that ask for it. Pre-built SQL from shared/config
    # contains regex quantifiers like {4} and {0,4}, which str.format would
    # explode on.
    if '{p}' in sql:
        sql = sql.format(p=PROJECT)
    return list(client.query(sql, job_config=cfg).result())


def check_metric(client, name: str, sql: str, start, end,
                 threshold=None, direction: str = 'below') -> Tuple[bool, List[str]]:
    lines: List[str] = []
    metric_rows = {r.game_date: float(r.metric) for r in _run(client, sql, start, end)
                   if r.metric is not None}
    churn_rows = {r.game_date: (float(r.young_share or 0.0), int(r.n_models))
                  for r in _run(client, CHURN_SQL, start, end)}
    days = sorted(set(metric_rows) & set(churn_rows))
    if len(days) < 30:
        lines.append(f"  SKIP  only {len(days)} overlapping days — not enough to judge")
        return True, lines

    metric = [metric_rows[d] for d in days]
    young = [churn_rows[d][0] for d in days]
    count = [float(churn_rows[d][1]) for d in days]

    rho_churn = spearman(metric, young)
    rho_count = spearman(metric, count)
    lines.append(f"  days={len(days)}  rho(metric, young_id_share)={rho_churn:+.3f}"
                 f"  rho(metric, model_count)={rho_count:+.3f}")

    coupled = abs(rho_churn) >= CHURN_RHO_LIMIT
    if coupled:
        lines.append(
            f"  COUPLED  |rho| vs churn {abs(rho_churn):.3f} >= {CHURN_RHO_LIMIT} — "
            f"this metric's LEVEL is a property of which models are running, not of "
            f"the market. That is not automatically a defect: it is true of every "
            f"model-derived quantity here, and no amount of quarantining removes it."
        )
    if abs(rho_churn) > abs(rho_count) * 3 and abs(rho_churn) > 0.3:
        lines.append(
            "  NOTE  churn coupling far exceeds headcount coupling — measuring model "
            "COUNT would under-read this problem, as one review did by 6x."
        )

    # The question that decides safety: can ordinary configuration churn move
    # the metric far enough to cross the threshold?
    if threshold is None:
        lines.append("  NOTE  no threshold registered — coupling reported only")
        return True, lines

    n = len(metric)
    mean = sum(metric) / n
    sd = (sum((v - mean) ** 2 for v in metric) / n) ** 0.5
    floor, ceil = min(metric), max(metric)
    edge_val = floor if direction == 'below' else ceil
    rel = abs(edge_val - threshold) / edge_val if edge_val else float('inf')
    lines.append(
        f"  threshold={threshold} ({direction})  observed floor/ceiling="
        f"{floor:.3f}/{ceil:.3f}  daily sd={sd:.3f}  clears by {rel * 100:.0f}%"
    )

    crossed = (direction == 'below' and floor < threshold) or \
              (direction == 'above' and ceil > threshold)
    if crossed:
        lines.append(
            "  FAIL  lived behaviour already crosses the threshold. A guard here "
            "fires on configuration, not on the world — which is exactly how the "
            "2026-08-19 halt came to be calibrated on a fleet swap."
        )
        return False, lines
    if rel < SAFE_RELATIVE_MARGIN:
        lines.append(
            f"  FAIL  only {rel * 100:.0f}% clear of lived behaviour (need "
            f"{SAFE_RELATIVE_MARGIN * 100:.0f}%). Enabling a model or letting an "
            f"experiment write rows could cross this bar. Move the threshold "
            f"outside lived behaviour, or stop gating on this metric."
        )
        return False, lines
    if coupled:
        lines.append(
            f"  OK    coupled, but the threshold clears lived behaviour by "
            f"{rel * 100:.0f}%, so churn cannot plausibly reach it. That trade — "
            f"keep the metric, move the bar far out of reach — is what the "
            f"2026-08-21 demotion chose deliberately."
        )
    else:
        lines.append(f"  OK    not churn-coupled; clears by {rel * 100:.0f}%")
    return True, lines


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--start', required=True, help='YYYY-MM-DD')
    ap.add_argument('--end', required=True, help='YYYY-MM-DD')
    ap.add_argument('--metric', help='check only this registered metric')
    args = ap.parse_args()

    from datetime import date
    start = date.fromisoformat(args.start)
    end = date.fromisoformat(args.end)

    # The shipped basis is defined in one place; import it rather than copying.
    from shared.config.edge_halt import build_daily_edge_query
    # Wrap rather than rewrite: the shipped query is the source of truth and a
    # string-surgery approach silently rots the moment it is edited.
    inner = (build_daily_edge_query(PROJECT)
             .replace('@series_start', '@start')
             .replace('@target_date', 'DATE_ADD(@end, INTERVAL 1 DAY)'))
    GUARD_METRICS['edge_median_warm_basis']['sql'] = (
        f"SELECT game_date, edge_med_7d AS metric FROM (\n{inner}\n) "
        f"WHERE edge_med_7d IS NOT NULL"
    )

    client = _client()
    failed = False
    for name, spec in GUARD_METRICS.items():
        if args.metric and name != args.metric:
            continue
        print(f"\n{name} — {spec['description']}")
        sql = spec['sql']
        if not sql:
            print("  SKIP  no SQL registered")
            continue
        try:
            ok, lines = check_metric(client, name, sql, start, end,
                                     spec.get('threshold'),
                                     spec.get('direction', 'below'))
        except Exception as e:                     # noqa: BLE001 - report, don't crash CI
            print(f"  ERROR {e}")
            continue
        for line in lines:
            print(line)
        if spec.get('historical'):
            print("  (historical witness — reported, does not fail the run)")
            continue
        failed = failed or not ok

    print("\n" + ("FAILED — a guard threshold sits within reach of configuration churn"
                  if failed else
                  "OK — every guard threshold is out of reach of configuration churn"))
    return 1 if failed else 0


if __name__ == '__main__':
    sys.exit(main())
